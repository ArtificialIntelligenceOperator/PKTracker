-- Линия игрока и размер перекрываемой ставки (продолжение ContextVersion 2).
--
-- Отдельной миграцией, а не правкой 003: та уже применена к базам, а применённые миграции
-- не редактируются — иначе у одних схема одна, у других другая, и обе считают себя v3.
--
-- line_bits: собственная линия игрока на постфлопе (BXB, XCF, ...), по 3 бита на улицу
-- (флоп - младшие; 0 не действовал, 1 X, 2 B, 3 C, 4 R). Линия живёт сразу на трёх улицах,
-- а точка решения видит только свою, поэтому её приходится нести с собой.
--
-- facing_amount: ставка на улице, которую игрок перекрывает. Из to_call её не получить - у BB
-- часть уже стоит блайндом, - а без неё не отличить минрейз от овербета и «опен 3-5x» от «опена 2bb».

ALTER TABLE hand_decisions
    ADD COLUMN IF NOT EXISTS line_bits     smallint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS facing_amount bigint   NOT NULL DEFAULT 0;

-- Значения появляются только после полного ребилда: они восстанавливаются из текста раздачи.
