--
-- hand_strength хранит категорию эвалюатора («пара», «две пары») - для разбора игры этого мало:
-- оверпара и младшая пара обе «пара». made_hand: младший байт - класс относительно борда
-- (оверкарты, карманка ниже борда, младшая/средняя/топ-пара, оверпара, две пары, трипс, сет, ...),
-- биты 0x100 / 0x200 / 0x400 - флеш-дро, двусторонний стрит-дро, гатшот; 0x800 - топ-пара с кикером
-- от валета (ContextVersion 6). 0 - карты неизвестны.
-- Значения появляются только после полного ребилда (rebuild --full): они считаются по картам из текста раздачи.

ALTER TABLE hand_decisions
    ADD COLUMN IF NOT EXISTS made_hand smallint NOT NULL DEFAULT 0;
